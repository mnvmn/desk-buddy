static inline int glyph_idx(char c) {
  if (c >= '0' && c <= '9') return c - '0';
  if (c >= 'A' && c <= 'H') return 10 + (c - 'A');
  if (c == ' ') return 18;
  if (c >= 'K' && c <= 'Q') return 19 + (c - 'K');
  if (c >= 'R' && c <= 'W') return 26 + (c - 'R');
  if (c == 'Y') return 32;
  if (c == '-') return 33;
  if (c == '.') return 34;
  if (c == ':') return 35;
  if (c == '/') return 36;
  if (c == 'h') return 37;   // countdown suffix ("5.5h")
  if (c == 'I') return 38;   // city names (BRATISLAVA)
  if (c == 'J') return 39;
  /* v2 extras (match web/panel_v2.html) */
  if (c == '~') return 40;
  if ((unsigned char)c == 0xB0) return 41;  // '°' single-byte (written as \xB0 in strings)
  if (c == '>') return 42;
  if (c == '_') return 43;
  if (c == 'm') return 44;
  if (c == 's') return 45;
  return -1;
}


static inline int put_text(int x, int y, const char *s, uint16_t color, int sc) {
  int cx = x;
  for (; *s; s++) {
    int gi = glyph_idx(*s);
    if (gi < 0) {  // D17 guard: warn instead of silently dropping a glyph
      Serial.printf("font: missing glyph for 0x%02x\n", (unsigned)(unsigned char)*s);
      continue;
    }
    for (int r = 0; r < 7; r++)
      for (int c = 0; c < 5; c++)
        if (GLYPHS[gi][r] & (1 << (4 - c))) {
          for (int dy = 0; dy < sc; dy++)
            for (int dx = 0; dx < sc; dx++)
              cv_set(cx + c * sc + dx, y + r * sc + dy, color);
        }
    cx += 6 * sc;
  }
  return cx;
}


static inline int text_w(const char *s, int sc) { return (int)strlen(s) * 6 * sc; }

