#!/usr/bin/env python3
"""Generate le_dercainfo.h for fw/weather_test — TLS trust anchors as DER.

The panel talks to two HTTPS hosts, each with a different CA:
  ISRG_ROOT_X1  (Let's Encrypt)  -> api.open-meteo.com   (weather)
  ISRG_ROOT_YR  (Let's Encrypt)  -> api.open-meteo.com   (weather)
  SECTIGO_R46   (Sectigo)        -> imhd.sk              (travel, direct fetch)
The server sends its own intermediate(s); we embed only the trust roots.

WHY DER, NOT PEM:
  The prebuilt esp32-arduino-libs (idf-release_v5.5, platform 3.3.3) that this
  board compiles against has a PEM parser that rejects the LE chain PEMs
  (mbedtls_x509_crt_parse -> MBEDTLS_ERR_X509_BAD_INPUT_DATA, -0x2180) even
  though the host openssl parses the identical bytes, and even though the SAME
  lib's mbedtls_x509_crt_parse_der accepts the identical cert as DER. The
  Arduino WiFiClientSecure wrapper feeds PEM, so its verified TLS can never
  work on this build. Feeding DER trust anchors directly to mbedTLS (the
  firmware uses raw mbedTLS) verifies cleanly (verify flags 0x00000000).

Usage:  python tools/gen_le_dercainfo.py NAME=file.der [NAME=file.pem ...]
        (name = C identifier for the anchor, e.g. ISRG_ROOT_X1; order = emit order)

Recapture a host's chain (the device may see a different chain than the dev box):
  openssl s_client -connect imhd.sk:443 -servername imhd.sk -showcerts
The ROOT is the self-signed cert that signs the server's topmost intermediate;
grab it from the intermediate's AIA "CA Issuers" URL (a .p7c bundle).

Rotating: re-run when an embedded root expires (X1: 2035, YR1: 2028, R46: 2034).
"""
import os, subprocess, sys

DEV = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # epaper-panel-weather/
OUTS = [os.path.join(DEV, 'fw', 'weather_test', 'le_dercainfo.h')]


def der_bytes(path):
    if path.lower().endswith('.der'):
        return open(path, 'rb').read()
    # accept .pem: convert via openssl
    der = path[:-4] + '.der' if path.lower().endswith('.pem') else path + '.der'
    subprocess.run(['openssl', 'x509', '-in', path, '-outform', 'DER', '-out', der],
                   check=True, capture_output=True)
    return open(der, 'rb').read()


def c_array(name, b):
    line = ', '.join(hex(x) for x in b)
    return f'static const uint8_t {name}[] = {{ {line} }};'


def main(pairs):
    names, bytes_ = [], []
    for pair in pairs:
        name, path = pair.split('=', 1)
        names.append(name)
        bytes_.append(der_bytes(path))
    blocks = [c_array(n, b) for n, b in zip(names, bytes_)]
    entry = ',\n'.join('  { %s, sizeof(%s) }' % (n, n) for n in names)
    hdr = (
        '// AUTO-GENERATED by tools/gen_le_dercainfo.py -- do not edit by hand.\n'
        '// TLS trust anchors (DER) for the panel\'s HTTPS hosts:\n'
        '//   ISRG_ROOT_X1 / ISRG_ROOT_YR  (Let\'s Encrypt) -> api.open-meteo.com\n'
        '//   SECTIGO_R46                  (Sectigo)        -> imhd.sk\n'
        '// DER, not PEM: this esp32-arduino build\'s PEM parser rejects the\n'
        '// chain PEMs (BAD_INPUT_DATA); its DER parser + raw mbedTLS verify\n'
        '// cleanly. Each server supplies its intermediates; we trust the roots.\n'
        '#ifndef LE_DERCINFO_H\n'
        '#define LE_DERCINFO_H\n\n'
        '#include <stdint.h>\n\n'
        + '\n'.join(blocks) + '\n\n'
        'struct trust_anchor { const uint8_t *der; size_t len; };\n'
        'static const struct trust_anchor TRUST_ANCHORS[] = {\n'
        + entry + '\n};\n'
        '#endif // LE_DERCINFO_H\n'
    )
    for out in OUTS:
        with open(out, 'w', newline='\n') as f:
            f.write(hdr)
        print('wrote', out, len(hdr), 'bytes', '(%d anchors: %s)' % (len(names), ', '.join(names)))


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit('usage: gen_le_dercainfo.py NAME=file.der [NAME=file.pem ...]')
    main(sys.argv[1:])
