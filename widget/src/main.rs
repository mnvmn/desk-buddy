//! DeskBuddy Windows widget — M3: multi-server, data-driven floating card.
//!
//! Standard Rust GUI setup (`eframe`/`egui`, 0.36): a `BuddyApp` that owns
//! the shared `WidgetState` (one `BuddyState` per inference server), a
//! background `poller` thread feeding it from `GET /slots` (hot) + `/props`
//! (once) + `/metrics` (slow) **per server**, and a borderless translucent
//! card that stacks the servers vertically (top = first).
//!
//! The server list and poll cadence come from a **config file** (see
//! `config.rs`) so adding a server is an edit, not a recompile. The window
//! grows vertically to fit however many servers are configured (one 320-wide
//! row each).
//!
//! The card has two **display modes** (`WidgetState::display_mode`, shared
//! across all rows):
//!   * **Data** (default) — one row per server, chosen by that server's
//!     `BuddyState::phase()` (generating / prompting / idle / down): status
//!     dot + big number left, model + capacity right, leftover line, tok/s
//!     sparkline + session footnote, dim host footer.
//!   * **Scene** — the full card becomes pixel art ("Plumber's run") showing
//!     **combined activity**: one band per server, stacked, each in its own
//!     phase (busy sprints, calm level when idle, piranha plant when down)
//!     — blits
//!     of the generated bitmaps in `scene_assets` (see `shared/scene-assets/`).
//!
//! The mode is toggled by **clicking anywhere on the card content** (the
//! drag strip and the close × are not content); the right-click menu on the
//! close button offers it explicitly too.
#![windows_subsystem = "windows"]
